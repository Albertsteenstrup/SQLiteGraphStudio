/// Values shared by SQLite and PostgreSQL result/table surfaces. The original
/// SQLite cases remain source-compatible; PostgreSQL-only values are retained
/// losslessly instead of coercing them to an opaque display string.
public enum SQLiteValue: Sendable, Hashable {
    case null
    case integer(Int64)
    case double(Double)
    case boolean(Bool)
    case exactNumeric(String)
    case text(String)
    case uuid(String)
    case dateTime(String)
    case json(String)
    case array(String)
    case blob(Data)

    public static func binary(_ data: Data) -> Self {
        .blob(data)
    }

    public init(databaseValue: DatabaseValue) {
        switch databaseValue.storage {
        case .null:
            self = .null
        case .int64(let value):
            self = .integer(value)
        case .double(let value):
            self = .double(value)
        case .string(let value):
            self = .text(value)
        case .blob(let value):
            self = .blob(value)
        }
    }

    public var displayText: String {
        switch self {
        case .null:
            return "NULL"
        case .integer(let value):
            return String(value)
        case .double(let value):
            return value.formatted(.number.precision(.fractionLength(0...4)))
        case .boolean(let value):
            return value ? "TRUE" : "FALSE"
        case .exactNumeric(let value):
            return value
        case .text(let value):
            return value
        case .uuid(let value), .dateTime(let value), .json(let value), .array(let value):
            return value
        case .blob(let data):
            return "<\(data.count) bytes>"
        }
    }

    public var typeLabel: String {
        switch self {
        case .null:
            return "NULL"
        case .integer:
            return "INTEGER"
        case .double:
            return "REAL"
        case .boolean:
            return "BOOLEAN"
        case .exactNumeric:
            return "NUMERIC"
        case .text:
            return "TEXT"
        case .uuid:
            return "UUID"
        case .dateTime:
            return "DATE/TIME"
        case .json:
            return "JSON"
        case .array:
            return "ARRAY"
        case .blob:
            return "BLOB"
        }
    }

    public var editorText: String {
        switch self {
        case .null:
            return "NULL"
        case .integer(let value):
            return String(value)
        case .double(let value):
            return String(value)
        case .boolean(let value):
            return value ? "true" : "false"
        case .exactNumeric(let value):
            return value
        case .text(let value):
            return value
        case .uuid(let value), .dateTime(let value), .json(let value), .array(let value):
            return value
        case .blob:
            return ""
        }
    }

    public var databaseValue: DatabaseValue {
        switch self {
        case .null:
            return .null
        case .integer(let value):
            return value.databaseValue
        case .double(let value):
            return value.databaseValue
        case .boolean(let value):
            return value.databaseValue
        case .exactNumeric(let value):
            return value.databaseValue
        case .text(let value):
            return value.databaseValue
        case .uuid(let value), .dateTime(let value), .json(let value), .array(let value):
            return value.databaseValue
        case .blob(let value):
            return value.databaseValue
        }
    }
}

