    ) {
        self.name = name
        self.host = host
        self.port = port
        self.database = database
        self.username = username
        self.tlsMode = tlsMode
    }

    private enum CodingKeys: String, CodingKey {
        case name
        case host
        case port
        case database
        case username
        case tlsMode
    }

    public init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        self.name = try container.decodeIfPresent(String.self, forKey: .name)
        self.host = try container.decode(String.self, forKey: .host)
        self.port = try container.decodeIfPresent(Int.self, forKey: .port) ?? 5432
        self.database = try container.decode(String.self, forKey: .database)
        self.username = try container.decode(String.self, forKey: .username)
        self.tlsMode = try container.decodeIfPresent(PostgresTLSMode.self, forKey: .tlsMode) ?? .required
    }

    public func encode(to encoder: Encoder) throws {
        var container = encoder.container(keyedBy: CodingKeys.self)
        try container.encodeIfPresent(name, forKey: .name)
        try container.encode(host, forKey: .host)
        try container.encode(port, forKey: .port)
        try container.encode(database, forKey: .database)
        try container.encode(username, forKey: .username)
        try container.encode(tlsMode, forKey: .tlsMode)
    }

    public var configuration: PostgresConnectionConfiguration {
        PostgresConnectionConfiguration(
            host: host,
            port: port,
            database: database,
            username: username,
            tlsMode: tlsMode
        )
    }

    public var displayName: String {
        let trimmedName = name?.trimmingCharacters(in: .whitespacesAndNewlines) ?? ""
        return trimmedName.isEmpty ? configuration.database : trimmedName
    }
}

