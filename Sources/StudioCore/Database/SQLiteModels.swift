public enum SQLiteObjectType: String, Sendable, Hashable, CaseIterable {
    case table
    case partitionedTable
    case view
    case materializedView
    case virtual
    case shadow
    case unknown

    init(rawDatabaseType: String) {
        switch rawDatabaseType.lowercased() {
        case "table":
            self = .table
        case "partitioned table", "partitionedtable":
            self = .partitionedTable
        case "view":
            self = .view
        case "materialized view", "materializedview":
            self = .materializedView
        case "virtual":
            self = .virtual
        case "shadow":
            self = .shadow
        default:
            self = .unknown
        }
    }
}

