public struct SQLiteUserError: Error, Sendable, Hashable, Identifiable, LocalizedError {
    public enum Kind: String, Sendable, Hashable {
        case busy
        case constraint
        case readOnly
        case invalidInput
        case notFound
        case authentication
        case network
        case permission
        case timeout
        case syntax
        case missingCredential
        case generic
    }

    public let kind: Kind
    public let message: String
    public let recoverySuggestion: String?

    public init(kind: Kind, message: String, recoverySuggestion: String? = nil) {
        self.kind = kind
        self.message = message
        self.recoverySuggestion = recoverySuggestion
    }

    public var id: String {
        "\(kind.rawValue):\(message)"
    }

    public var errorDescription: String? {
        message
    }

    public static func from(_ error: any Error) -> SQLiteUserError {
        if let userError = error as? SQLiteUserError {
            return userError
        }

        if let dbError = error as? DatabaseError {
            let message = dbError.message ?? dbError.resultCode.description
            switch dbError.resultCode {
            case .SQLITE_BUSY:
                return SQLiteUserError(
                    kind: .busy,
                    message: message,
                    recoverySuggestion: "The database is busy. Retry the change after pending work finishes."
                )
            case .SQLITE_CONSTRAINT:
                return SQLiteUserError(kind: .constraint, message: message)
            case .SQLITE_READONLY:
                return SQLiteUserError(kind: .readOnly, message: message)
            default:
                return SQLiteUserError(kind: .generic, message: message)
            }
        }

        return SQLiteUserError(kind: .generic, message: error.localizedDescription)
    }
}

public typealias DatabaseUserError = SQLiteUserError

public func quoteIdentifier(_ value: String) -> String {
    "\"\(value.replacingOccurrences(of: "\"", with: "\"\""))\""
}

public func qualifiedIdentifier(schema: String, object: String) -> String {
    "\(quoteIdentifier(schema)).\(quoteIdentifier(object))"
}

func quoteStringLiteral(_ value: String) -> String {
    "'\(value.replacingOccurrences(of: "'", with: "''"))'"
}

func parseSQLiteValue(_ rawValue: String, for column: TableColumn, recognizesNullLiteral: Bool = true) throws -> SQLiteValue {
    let trimmed = rawValue.trimmingCharacters(in: .whitespacesAndNewlines)
    if recognizesNullLiteral && trimmed.uppercased() == "NULL" {
        if column.notNull {
            throw SQLiteUserError(kind: .invalidInput, message: "\(column.name) does not allow NULL values.")
        }
        return .null
    }

    switch column.affinity {
    case .integer:
        if let intValue = Int64(trimmed) {
            return .integer(intValue)
        }
        return .text(rawValue)
    case .real:
        if let doubleValue = Double(trimmed) {
            return .double(doubleValue)
        }
        return .text(rawValue)
    case .blob:
        throw SQLiteUserError(kind: .invalidInput, message: "Inline blob editing is not supported for \(column.name).")
    case .numeric:
        if let intValue = Int64(trimmed) {
            return .integer(intValue)
        }
        if let doubleValue = Double(trimmed) {
            return .double(doubleValue)
        }
        return .text(rawValue)
    case .text, .none:
        return .text(rawValue)
    }
}

extension TableCountState {
    static func forPage(query: TableQueryState, rowCount: Int, hasMore: Bool, exactCount: Int?) -> Self {
        let end = query.offset + rowCount
        if query.after != nil { return exactCount.map(Self.exact) ?? .unknown }
        if let exactCount, exactCount >= end + (hasMore ? 1 : 0) { return .exact(exactCount) }
        if hasMore { return .atLeast(end) }
        return rowCount > 0 || query.offset == 0 ? .exact(end) : .unknown
    }
}
