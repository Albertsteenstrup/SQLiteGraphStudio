        columns: [TableColumn],
        primaryKeyColumns: [String],
        rowIdentityStrategy: RowIdentityStrategy,
        isWithoutRowID: Bool,
        isEditable: Bool,
        rowCount: Int? = nil,
        indexes: [SchemaIndex] = [],
        triggers: [SchemaTrigger] = [],
        constraints: [SchemaConstraint] = [],
        generatedColumns: [GeneratedColumnInfo] = [],
        schemaName: String? = nil,
        objectName: String? = nil,
        hasInheritanceChildren: Bool = false
    ) {
        self.id = name
        self.name = name
        self.objectType = objectType
        self.columns = columns
        self.primaryKeyColumns = primaryKeyColumns
        self.rowIdentityStrategy = rowIdentityStrategy
        self.isWithoutRowID = isWithoutRowID
        self.isEditable = isEditable
        self.rowCount = rowCount
        self.indexes = indexes
        self.triggers = triggers
        self.constraints = constraints
        self.generatedColumns = generatedColumns
        self.schemaName = schemaName
        self.objectName = objectName ?? name
        self.hasInheritanceChildren = hasInheritanceChildren
    }

    public init(
        name: String,
        schemaName: String?,
        objectName: String?,
        objectType: SQLiteObjectType,
        columns: [TableColumn],
        primaryKeyColumns: [String],
        rowIdentityStrategy: RowIdentityStrategy,
        isWithoutRowID: Bool,
        isEditable: Bool,
        rowCount: Int? = nil,
        indexes: [SchemaIndex] = [],
        triggers: [SchemaTrigger] = [],
        constraints: [SchemaConstraint] = [],
        generatedColumns: [GeneratedColumnInfo] = [],
        hasInheritanceChildren: Bool = false
    ) {
        self.init(
            name: name,
            objectType: objectType,
            columns: columns,
            primaryKeyColumns: primaryKeyColumns,
            rowIdentityStrategy: rowIdentityStrategy,
            isWithoutRowID: isWithoutRowID,
            isEditable: isEditable,
            rowCount: rowCount,
            indexes: indexes,
            triggers: triggers,
            constraints: constraints,
            generatedColumns: generatedColumns,
            schemaName: schemaName,
            objectName: objectName,
            hasInheritanceChildren: hasInheritanceChildren
        )
    }

    public var summary: TableSummary {
        TableSummary(
            name: name,
            objectType: objectType,
            isEditable: isEditable,
            columnCount: columns.count,
            rowCount: rowCount,
            schemaName: schemaName,
            objectName: objectName
        )
    }

    public var searchableColumns: [TableColumn] {
        columns.filter { $0.affinity != .blob }
    }

    public var identityColumns: [TableColumn] {
        columns.filter(\.isIdentity)
    }

    public var fallbackSortColumns: [String] {
        switch rowIdentityStrategy {
        case .primaryKey:
            return primaryKeyColumns
        case .rowID:
            return ["_rowid_"]
        case .readOnly:
            return columns.map(\.name)
        }
    }

    public var qualifiedSQLIdentifier: String {
        if let schemaName {
            return qualifiedIdentifier(schema: schemaName, object: objectName)
        }
        return quoteIdentifier(name)
    }

    /// Key-based browsing and navigation address this physical table. Declarative
    /// partition roots retain their inclusive scope and tree-wide constraints.
    public var tableDataSQLSource: String {
        (schemaName != nil && objectType == .table && hasInheritanceChildren ? "ONLY " : "") + qualifiedSQLIdentifier
    }
}

