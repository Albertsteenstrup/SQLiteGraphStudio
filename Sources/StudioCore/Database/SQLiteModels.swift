public struct TableColumn: Identifiable, Sendable, Hashable {
    public let id: String
    public let name: String
    public let declaredType: String
    public let notNull: Bool
    public let defaultValueSQL: String?
    public let primaryKeyOrdinal: Int
    public let hiddenValue: Int
    public let identityKind: String
    /// PostgreSQL descriptors set this to false. SQLite keeps the historical
    /// affinity-based editability behavior when it is nil.
    public let editabilityOverride: Bool?

    public init(
        name: String,
        declaredType: String,
        notNull: Bool,
        defaultValueSQL: String?,
        primaryKeyOrdinal: Int,
        hiddenValue: Int,
        isEditable: Bool? = nil,
        identityKind: String = ""
    ) {
        self.id = name
        self.name = name
        self.declaredType = declaredType
        self.notNull = notNull
        self.defaultValueSQL = defaultValueSQL
        self.primaryKeyOrdinal = primaryKeyOrdinal
        self.hiddenValue = hiddenValue
        self.identityKind = identityKind
        self.editabilityOverride = isEditable
    }

    public var affinity: ColumnAffinity {
        ColumnAffinity(declaredType: declaredType)
    }

    public var isGenerated: Bool {
        hiddenValue != 0
    }

    public var isIdentity: Bool {
        !identityKind.isEmpty
    }

    public var identityLabel: String? {
        switch identityKind {
        case "a":
            return "GENERATED ALWAYS AS IDENTITY"
        case "d":
            return "GENERATED BY DEFAULT AS IDENTITY"
        default:
            return identityKind.isEmpty ? nil : "IDENTITY"
        }
    }

    public var isEditable: Bool {
        (editabilityOverride ?? true) && !isGenerated && affinity != .blob
    }

    public var typeLabel: String {
        declaredType.isEmpty ? affinity.rawValue.uppercased() : declaredType.uppercased()
    }

    public var canDropInSQLite: Bool {
        !isGenerated && primaryKeyOrdinal == 0
    }
}

