public struct PostgresConnectionConfiguration: Sendable, Hashable, Codable {
    public var host: String
    public var port: Int
    public var database: String
    public var username: String
    public var tlsMode: PostgresTLSMode

    public init(
        host: String,
        port: Int = 5432,
        database: String,
        username: String,
        tlsMode: PostgresTLSMode = .required
    ) {
        self.host = host.trimmingCharacters(in: .whitespacesAndNewlines)
        self.port = port
        self.database = database.trimmingCharacters(in: .whitespacesAndNewlines)
        self.username = username.trimmingCharacters(in: .whitespacesAndNewlines)
        self.tlsMode = tlsMode
    }

    public var canonicalIdentity: String {
        [
            host.lowercased(),
            String(port),
            database,
            username,
            tlsMode.rawValue,
        ].joined(separator: "\u{1F}")
    }

    public var stableStorageKey: String {
        SHA256.hash(data: Data(canonicalIdentity.utf8))
            .map { String(format: "%02x", $0) }
            .joined()
    }
}

public enum DatabaseTarget: Sendable, Hashable, Codable {
    case sqlite(URL)
    case postgres(PostgresConnectionConfiguration)

    private enum CodingKeys: String, CodingKey {
        case kind
        case url
        case configuration
    }

    private enum Kind: String, Codable {
        case sqlite
        case postgres
    }

    public init(from decoder: Decoder) throws {
        let container = try decoder.container(keyedBy: CodingKeys.self)
        switch try container.decode(Kind.self, forKey: .kind) {
        case .sqlite:
            self = .sqlite(try container.decode(URL.self, forKey: .url).standardizedFileURL)
        case .postgres:
            self = .postgres(try container.decode(PostgresConnectionConfiguration.self, forKey: .configuration))
        }
    }

    public func encode(to encoder: Encoder) throws {
        var container = encoder.container(keyedBy: CodingKeys.self)
        switch self {
        case .sqlite(let url):
            try container.encode(Kind.sqlite, forKey: .kind)
            try container.encode(url.standardizedFileURL, forKey: .url)
        case .postgres(let configuration):
            try container.encode(Kind.postgres, forKey: .kind)
            try container.encode(configuration, forKey: .configuration)
        }
    }

    public var identity: String {
        switch self {
        case .sqlite(let url):
            return "sqlite:" + url.standardizedFileURL.path
        case .postgres(let configuration):
            return "postgres:" + configuration.canonicalIdentity
        }
    }

    public var stableStorageKey: String {
        switch self {
        case .sqlite:
            return identity
        case .postgres(let configuration):
            return "postgres-" + configuration.stableStorageKey
        }
    }

    public var fileURL: URL? {
        if case .sqlite(let url) = self {
            return url.standardizedFileURL
        }
        return nil
    }

    public var displayName: String {
        switch self {
        case .sqlite(let url):
            return url.lastPathComponent
        case .postgres(let configuration):
            return "PostgreSQL · " + configuration.database
        }
    }

    public var isPostgres: Bool {
        if case .postgres = self { return true }
        return false
    }
}

/// A user-selected PostgreSQL document. It describes only the endpoint; the
